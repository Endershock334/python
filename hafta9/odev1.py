# Öğrencilerden para_ekle adında bir fonksiyon yazmaları istenir.

def para_ekle(mevcut_para, kazanilan_para):
    toplam_para = mevcut_para + kazanilan_para
    return toplam_para

sonuc = para_ekle(234, 46)
print("Toplam para:", sonuc)

